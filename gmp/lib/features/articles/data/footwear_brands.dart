  static FootwearBrand? findByName(String? name) {
    if (name == null || name.trim().isEmpty) return null;
    final needle = name.trim().toLowerCase();
    for (final brand in all) {
      if (brand.name.toLowerCase() == needle) return brand;
    }
    return null;
  }

  static String footwearTypeFor(String brandName) {
    return findByName(brandName)?.footwearType ?? 'everyday';
  }

  static List<FootwearBrand> search(String query) {
    final q = query.trim().toLowerCase();
    if (q.isEmpty) return all;
    return all.where((b) => b.name.toLowerCase().contains(q)).toList();
  }
